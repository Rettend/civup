import type { CloudflareStorageLocation, CloudflareTargetName } from '../../../config/cloudflare-targets.ts'
import { mkdir } from 'node:fs/promises'
import { dirname } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import iconSet from '@iconify-json/fluent-emoji/icons.json'
import emojiData from 'unicode-emoji-json'
import { resolveCloudflareTargetName } from '../../../config/cloudflare-targets.ts'
import { createMaintenanceClient } from './maintenance-cloudflare.ts'

const OUTPUT_PATH = fileURLToPath(new URL('../src/constants/tournament-emoji-icons.ts', import.meta.url).href)
const SKIN_TONE_SUFFIX_BY_MODIFIER: Record<string, string> = {
  '\u{1F3FB}': 'light',
  '\u{1F3FC}': 'medium-light',
  '\u{1F3FD}': 'medium',
  '\u{1F3FE}': 'medium-dark',
  '\u{1F3FF}': 'dark',
}
const SKIN_TONE_MODIFIER_PATTERN = /[\u{1F3FB}-\u{1F3FF}]/gu
const VARIATION_SELECTOR_16 = '\uFE0F'
const unicodeEmojiData = emojiData as Record<string, UnicodeEmojiEntry>
const graphemeSegmenter =
  typeof Intl.Segmenter === 'function' ? new Intl.Segmenter(undefined, { granularity: 'grapheme' }) : null

interface NameRow {
  display_name: string
}
interface UnicodeEmojiEntry {
  name: string
  slug: string
}
interface EmojiMetadata {
  entry: UnicodeEmojiEntry
  toneSuffix: string | null
}
interface IconData {
  width: number
  height: number
  body: string
}
interface IconifyIconData {
  width?: number
  height?: number
  body?: string
  parent?: string
  hFlip?: boolean
  vFlip?: boolean
  rotate?: number
}

interface DatabaseEmojiSource {
  tournamentId: string
  target: CloudflareTargetName
  location: CloudflareStorageLocation
}

export interface TournamentEmojiOptions {
  database: DatabaseEmojiSource | null
  emojis: string[]
  files: string[]
  allowEmpty: boolean
}

if (import.meta.main) await generateTournamentEmojiIcons(parseTournamentEmojiOptions(Bun.argv.slice(2)))

async function generateTournamentEmojiIcons(options: TournamentEmojiOptions) {
  const sourceTexts = await collectSourceTexts(options)
  const emojis = collectEmojiCandidates(sourceTexts)
  const sortedEmojis = [...emojis].sort()
  const unmapped = new Map<string, string>()

  const iconEntries = sortedEmojis.map(emoji => {
    const metadata = resolveEmojiMetadata(emoji)
    if (!metadata) {
      unmapped.set(emoji, 'missing Unicode emoji metadata')
      return null
    }

    const iconName = resolveFluentIconName(metadata)
    if (!iconName) {
      unmapped.set(emoji, `no fluent-emoji icon for ${metadata.entry.slug}`)
      return null
    }

    const icon = resolveFluentIcon(iconName)
    if (!icon) throw new Error(`Missing fluent-emoji icon: ${iconName}`)
    return [emoji, icon, iconName] as const
  })

  if (unmapped.size > 0) {
    throw new Error(
      [
        'Unable to map tournament emoji to Fluent Emoji icons:',
        ...[...unmapped].sort().map(([emoji, reason]) => `- ${emoji}: ${reason}`),
        'Update unicode-emoji-json/@iconify-json/fluent-emoji or add a generic name transform.',
      ].join('\n'),
    )
  }

  const icons = Object.fromEntries(iconEntries.flatMap(entry => (entry ? [[entry[0], entry[1]]] : [])))
  const iconNames = Object.fromEntries(iconEntries.flatMap(entry => (entry ? [[entry[0], entry[2]]] : [])))

  await mkdir(dirname(OUTPUT_PATH), { recursive: true })
  await Bun.write(
    OUTPUT_PATH,
    `// Generated by apps/bot/scripts/generate-tournament-emoji-icons.ts. Do not edit manually.
export interface TournamentEmojiIcon {
  width: number
  height: number
  body: string
}

export const TOURNAMENT_EMOJI_ICONS = ${JSON.stringify(icons, null, 2)} as const satisfies Record<string, TournamentEmojiIcon>
`,
  )

  console.log(JSON.stringify({ outputPath: OUTPUT_PATH, emojis: sortedEmojis, iconNames }, null, 2))
}

async function collectSourceTexts(options: TournamentEmojiOptions): Promise<string[]> {
  const texts: string[] = []
  if (options.database) {
    texts.push(
      ...(
        await runD1<NameRow>(
          `
      SELECT display_name
      FROM tournament_players
      WHERE tournament_id = ${sqlString(options.database.tournamentId)} AND confirmed = 1;
    `,
          options.database,
        )
      ).map(row => row.display_name),
    )
  }

  texts.push(...options.emojis)

  for (const file of options.files) texts.push(await Bun.file(file).text())

  if (texts.length === 0 && !options.allowEmpty) {
    const existingEmojis = await collectExistingOutputEmojis()
    texts.push(...existingEmojis)
    if (existingEmojis.length === 0) {
      throw new Error(
        'No emoji sources found. Pass --emoji <emoji>, CSV/text files, or --d1-tournament-id <id> --target <target> --local|--remote. Use --allow-empty to generate an empty set.',
      )
    }
  }

  return texts
}

async function collectExistingOutputEmojis(): Promise<string[]> {
  const file = Bun.file(OUTPUT_PATH)
  if (!(await file.exists())) return []
  const module = (await import(`${pathToFileURL(OUTPUT_PATH).href}?cache=${Date.now()}`).catch(() => null)) as {
    TOURNAMENT_EMOJI_ICONS?: Record<string, unknown>
  } | null
  return Object.keys(module?.TOURNAMENT_EMOJI_ICONS ?? {})
}

function collectEmojiCandidates(texts: string[]): Set<string> {
  const result = new Set<string>()
  for (const text of texts) {
    for (const grapheme of splitGraphemes(text)) {
      if (isEmojiCandidate(grapheme)) result.add(grapheme)
    }
  }
  return result
}

function splitGraphemes(value: string): string[] {
  if (!graphemeSegmenter) return Array.from(value)
  return [...graphemeSegmenter.segment(value)].map(segment => segment.segment)
}

function isEmojiCandidate(value: string): boolean {
  if (resolveEmojiMetadata(value)) return true
  return /\p{Extended_Pictographic}|\p{Regional_Indicator}|\u20E3/u.test(value)
}

function resolveEmojiMetadata(value: string): EmojiMetadata | null {
  const direct = unicodeEmojiData[value]
  if (direct) return { entry: direct, toneSuffix: null }

  const withoutTone = value.replace(SKIN_TONE_MODIFIER_PATTERN, '')
  const toneSuffix = resolveSkinToneSuffix(value)
  if (toneSuffix && withoutTone !== value) {
    const toned = findUnicodeEmojiEntry(withoutTone)
    if (toned) return { entry: toned, toneSuffix }
  }

  const entry = findUnicodeEmojiEntry(value)
  return entry ? { entry, toneSuffix: null } : null
}

function findUnicodeEmojiEntry(value: string): UnicodeEmojiEntry | null {
  const candidates = [value, value.replaceAll(VARIATION_SELECTOR_16, ''), addEmojiVariationSelectors(value)]
  for (const candidate of unique(candidates)) {
    const entry = unicodeEmojiData[candidate]
    if (entry) return entry
  }
  return null
}

function addEmojiVariationSelectors(value: string): string {
  return splitGraphemes(value)
    .map(grapheme => {
      if (grapheme.includes(VARIATION_SELECTOR_16)) return grapheme
      return /\p{Extended_Pictographic}/u.test(grapheme) ? `${grapheme}${VARIATION_SELECTOR_16}` : grapheme
    })
    .join('')
}

function resolveSkinToneSuffix(value: string): string | null {
  for (const modifier of value.match(SKIN_TONE_MODIFIER_PATTERN) ?? []) {
    const suffix = SKIN_TONE_SUFFIX_BY_MODIFIER[modifier]
    if (suffix) return suffix
  }
  return null
}

function resolveFluentIconName(metadata: EmojiMetadata): string | null {
  for (const candidate of buildFluentIconNameCandidates(metadata)) {
    if (hasFluentIcon(candidate)) return candidate
  }
  return null
}

function buildFluentIconNameCandidates(metadata: EmojiMetadata): string[] {
  const baseCandidates = unique(
    [toIconName(metadata.entry.slug), toIconName(metadata.entry.name)].flatMap(name => expandIconNameVariants(name)),
  )

  if (!metadata.toneSuffix) return baseCandidates
  return unique(baseCandidates.flatMap(name => [`${name}-${metadata.toneSuffix}`, name]))
}

function expandIconNameVariants(name: string): string[] {
  const names = new Set<string>([name])
  // Snapshot each stage: iterating the changing Set would visit added variants.
  const blondVariants = [...names]
  for (const candidate of blondVariants) names.add(candidate.replace(/blond/g, 'blonde'))
  const clockVariants = [...names]
  for (const candidate of clockVariants) names.add(candidate.replace(/-o-clock/g, '-oclock'))
  const personVariants = [...names]
  for (const candidate of personVariants) {
    const personSuffix = candidate.match(/^(.*)-(person|man|woman)$/)
    if (personSuffix) names.add(`${personSuffix[2]}-${personSuffix[1]}`)
    names.add(`person-${candidate}`)
    names.add(`man-${candidate}`)
    names.add(`woman-${candidate}`)
  }
  return [...names]
}

function toIconName(value: string): string {
  return value
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/['’]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
}

function hasFluentIcon(name: string): boolean {
  return name in iconSet.icons || name in (iconSet.aliases ?? {})
}

function resolveFluentIcon(name: string, seen = new Set<string>()): IconData | null {
  if (seen.has(name)) throw new Error(`Circular fluent-emoji alias: ${[...seen, name].join(' -> ')}`)
  seen.add(name)

  const icon = (iconSet.icons as Record<string, IconifyIconData>)[name]
  if (icon?.body) return normalizeIconData(icon)

  const alias = (iconSet.aliases as Record<string, IconifyIconData> | undefined)?.[name]
  if (!alias?.parent) return null

  const parent = resolveFluentIcon(alias.parent, seen)
  if (!parent) return null
  return {
    width: alias.width ?? parent.width,
    height: alias.height ?? parent.height,
    body: applyIconTransform(parent.body, alias, parent.width, parent.height),
  }
}

function normalizeIconData(icon: IconifyIconData): IconData {
  return {
    width: icon.width ?? iconSet.width ?? 32,
    height: icon.height ?? iconSet.height ?? 32,
    body: applyIconTransform(
      icon.body ?? '',
      icon,
      icon.width ?? iconSet.width ?? 32,
      icon.height ?? iconSet.height ?? 32,
    ),
  }
}

function applyIconTransform(body: string, icon: IconifyIconData, width: number, height: number): string {
  const hFlip = icon.hFlip === true
  const vFlip = icon.vFlip === true
  if (!hFlip && !vFlip) return body
  const x = hFlip ? width : 0
  const y = vFlip ? height : 0
  return `<g transform="translate(${x} ${y}) scale(${hFlip ? -1 : 1} ${vFlip ? -1 : 1})">${body}</g>`
}

function unique<T>(values: Iterable<T>): T[] {
  return [...new Set(values)]
}

async function runD1<T>(sql: string, source: DatabaseEmojiSource): Promise<T[]> {
  const { client } = createMaintenanceClient({ target: source.target }, source.location)
  return (await client.d1Query<T>(sql))[0]!.results
}

function sqlString(value: string): string {
  return `'${value.replace(/'/g, "''")}'`
}

export function parseTournamentEmojiOptions(args: readonly string[]): TournamentEmojiOptions {
  const options: TournamentEmojiOptions = { database: null, emojis: [], files: [], allowEmpty: false }
  let tournamentId: string | undefined
  let target: string | undefined
  let location: CloudflareStorageLocation | undefined
  for (let index = 0; index < args.length; index++) {
    const arg = args[index]!
    if (arg === '--allow-empty') {
      options.allowEmpty = true
      continue
    }
    if (arg === '--local' || arg === '--remote') {
      if (location) throw new Error('Choose exactly one of --local or --remote.')
      location = arg === '--local' ? 'local' : 'remote'
      continue
    }
    if (!arg.startsWith('--')) {
      options.files.push(arg)
      continue
    }
    const equals = arg.indexOf('=')
    const name = equals < 0 ? arg : arg.slice(0, equals)
    if (!['--d1-tournament-id', '--target', '--emoji'].includes(name)) throw new Error(`Unknown option: ${name}`)
    const value = equals < 0 ? args[++index] : arg.slice(equals + 1)
    if (!value?.trim() || value.startsWith('--')) throw new Error(`Provide a value for ${name}.`)
    if (name === '--emoji') {
      options.emojis.push(value)
    } else if (name === '--target') {
      if (target !== undefined) throw new Error('Provide --target only once.')
      target = value
    } else {
      if (tournamentId !== undefined) throw new Error('Provide --d1-tournament-id only once.')
      tournamentId = value
    }
  }
  if (tournamentId !== undefined) {
    if (target === undefined || location === undefined)
      throw new Error('Database sources require --target and exactly one of --local or --remote.')
    options.database = { tournamentId, target: resolveCloudflareTargetName(target), location }
  } else if (target !== undefined || location !== undefined) {
    throw new Error('Provide --d1-tournament-id when selecting a database target or storage location.')
  }
  return options
}
