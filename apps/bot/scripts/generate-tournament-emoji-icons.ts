const SKIN_TONE_SUFFIX_BY_MODIFIER: Record<string, string> = {
  '\u{1F3FB}': 'light',
  '\u{1F3FC}': 'medium-light',
  '\u{1F3FD}': 'medium',
  '\u{1F3FE}': 'medium-dark',
  '\u{1F3FF}': 'dark',
}
const SKIN_TONE_MODIFIER_PATTERN = /[\u{1F3FB}-\u{1F3FF}]/gu
const VARIATION_SELECTOR_16 = '\uFE0F'
const unicodeEmojiData = emojiData as Record<string, UnicodeEmojiEntry>
const graphemeSegmenter = typeof Intl.Segmenter === 'function'
  ? new Intl.Segmenter(undefined, { granularity: 'grapheme' })
  : null

interface D1Result<T> { results?: T[], success?: boolean, errors?: unknown[] }
interface NameRow { display_name: string }
interface UnicodeEmojiEntry { name: string, slug: string }
interface EmojiMetadata { entry: UnicodeEmojiEntry, toneSuffix: string | null }
interface IconData { width: number, height: number, body: string }
interface IconifyIconData { width?: number, height?: number, body?: string, parent?: string, hFlip?: boolean, vFlip?: boolean, rotate?: number }

